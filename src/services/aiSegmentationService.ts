/**
 * MAISHAA WORKSPACE 2 — REAL AI FOREGROUND SEGMENTATION ENGINE
 * Integrates pretrained deep-learning segmentation models:
 * 1. Google MediaPipe Selfie & Full-Body Segmentation (runs client-side via WASM/WebGL, isolates human subjects, hair, clothes, limbs)
 * 2. @imgly/background-removal IS-Net salient object matting (for general objects, products, animals)
 * 
 * Guarantees real AI segmentation. Never silently falls back to inaccurate color-distance algorithms.
 */

import { loadImageFromFile } from './bgRemoverService';

export interface AiSegmentationResult {
  alphaMask: Uint8Array;
  maskCanvas: HTMLCanvasElement;
  cutoutCanvas: HTMLCanvasElement;
  blob: Blob;
  modelUsed: 'mediapipe_person' | 'imgly_isnet';
  confidence?: number;
}

async function loadMediaPipeSelfieSegmentation(): Promise<any> {
  if (typeof window === 'undefined') return null;
  if ((window as any).SelfieSegmentation) {
    return (window as any).SelfieSegmentation;
  }

  // Inject script dynamically
  await new Promise<void>((resolve, reject) => {
    const existingScript = document.querySelector('script[src*="selfie_segmentation.js"]');
    if (existingScript) {
      if ((window as any).SelfieSegmentation) {
        resolve();
        return;
      }
      existingScript.addEventListener('load', () => resolve());
      existingScript.addEventListener('error', () => reject(new Error('Failed to load MediaPipe script')));
      return;
    }

    const script = document.createElement('script');
    script.src = '/mediapipe/selfie_segmentation.js';
    script.async = true;
    script.onload = () => resolve();
    script.onerror = () => reject(new Error('Failed to load /mediapipe/selfie_segmentation.js'));
    document.head.appendChild(script);
  });

  return (window as any).SelfieSegmentation || null;
}

/**
 * Executes Google MediaPipe Selfie & Person Segmentation.
 * Isolates entire foreground human subject (head, hair, face, scarf, clothing, hands, feet, shoes)
 * and accurately strips away background walls, ground, vegetation, and outdoor elements.
 */
export async function executeMediaPipeSegmentation(
  imgElement: HTMLImageElement,
  options: { modelSelection?: number } = {}
): Promise<AiSegmentationResult> {
  const w = Math.max(1, imgElement.naturalWidth || imgElement.width || 1);
  const h = Math.max(1, imgElement.naturalHeight || imgElement.height || 1);

  const SelfieSegmentationClass = await loadMediaPipeSelfieSegmentation();
  if (!SelfieSegmentationClass) {
    throw new Error('MediaPipe SelfieSegmentation library is unavailable in browser.');
  }

  // Optimize inference input for large images (e.g. 12MP 3060x4080 photos)
  // MediaPipe model operates at 256x256 tensor size; feeding >1280px causes WebGL texture overflow and lag.
  const maxInferenceDim = 1280;
  let inferenceSource: HTMLImageElement | HTMLCanvasElement = imgElement;
  if (Math.max(w, h) > maxInferenceDim) {
    const scale = maxInferenceDim / Math.max(w, h);
    const inferCanvas = document.createElement('canvas');
    inferCanvas.width = Math.max(64, Math.round(w * scale));
    inferCanvas.height = Math.max(64, Math.round(h * scale));
    const inferCtx = inferCanvas.getContext('2d');
    if (inferCtx) {
      inferCtx.drawImage(imgElement, 0, 0, inferCanvas.width, inferCanvas.height);
      inferenceSource = inferCanvas;
    }
  }

  return new Promise((resolve, reject) => {
    let hasResolved = false;
    const timeoutTimer = setTimeout(() => {
      if (!hasResolved) {
        hasResolved = true;
        try {
          segmenter.close();
        } catch {}
        reject(new Error('MediaPipe AI segmentation timed out (15s).'));
      }
    }, 15000);

    const segmenter = new SelfieSegmentationClass({
      locateFile: (file: string) => {
        // Point to locally served assets in /mediapipe/
        return `/mediapipe/${file}`;
      },
    });

    segmenter.setOptions({
      // 1 = Landscape / full-body portrait model (best for full people, standing portraits, and complex backgrounds)
      // 0 = General close-up selfie model
      modelSelection: options.modelSelection ?? 1,
      selfieMode: false,
    });

    segmenter.onResults((results: any) => {
      if (hasResolved) return;
      hasResolved = true;
      clearTimeout(timeoutTimer);

      try {
        if (!results.segmentationMask) {
          throw new Error('No segmentation mask was generated by the AI model.');
        }

        // Draw the raw AI mask to full original resolution canvas
        // Hardware bilinear scaling ensures smooth anti-aliased contours
        const maskCanvas = document.createElement('canvas');
        maskCanvas.width = w;
        maskCanvas.height = h;
        const maskCtx = maskCanvas.getContext('2d', { willReadFrequently: true });
        if (!maskCtx) throw new Error('2D Canvas Context unavailable');

        maskCtx.drawImage(results.segmentationMask as any, 0, 0, w, h);
        const maskImgData = maskCtx.getImageData(0, 0, w, h);
        const maskData = maskImgData.data;

        const totalPixels = w * h;
        const alphaMask = new Uint8Array(totalPixels);
        let foregroundPixelCount = 0;

        for (let i = 0; i < totalPixels; i++) {
          const p = i * 4;
          const rawConf = Math.max(maskData[p], maskData[p + 1], maskData[p + 2]);
          
          // Clean thresholding curve:
          // Completely cut off low-confidence background leakage (wall tiles, ground, vegetation < 40)
          // Solidify confident human subject (body, clothing, scarf, shoes, hair > 160)
          // Smooth anti-aliased gradient in transition band (40 to 160)
          let a = 0;
          if (rawConf <= 40) {
            a = 0;
          } else if (rawConf >= 160) {
            a = 255;
          } else {
            a = Math.round(((rawConf - 40) / (160 - 40)) * 255);
          }

          alphaMask[i] = a;
          if (a > 60) {
            foregroundPixelCount++;
          }
        }

        const coverageRatio = foregroundPixelCount / totalPixels;
        // Verify that a valid human subject was detected (between 0.3% and 99.5% of total image)
        if (foregroundPixelCount === 0 || coverageRatio < 0.003) {
          throw new Error('No foreground person was detected in the photograph by the person segmentation model.');
        }

        // Create the final cutout canvas preserving 100% of original photo RGB colors and textures
        const cutoutCanvas = document.createElement('canvas');
        cutoutCanvas.width = w;
        cutoutCanvas.height = h;
        const cutoutCtx = cutoutCanvas.getContext('2d', { willReadFrequently: true });
        if (!cutoutCtx) throw new Error('2D Canvas Context unavailable');

        cutoutCtx.drawImage(imgElement, 0, 0, w, h);
        const cutoutImgData = cutoutCtx.getImageData(0, 0, w, h);
        const cutoutData = cutoutImgData.data;

        // Apply segmentation alpha mask; zero out transparent pixels to drastically reduce PNG file size
        for (let i = 0; i < totalPixels; i++) {
          const a = alphaMask[i];
          const p = i * 4;
          if (a === 0) {
            cutoutData[p] = 0;
            cutoutData[p + 1] = 0;
            cutoutData[p + 2] = 0;
            cutoutData[p + 3] = 0;
          } else {
            cutoutData[p + 3] = a;
          }
        }
        cutoutCtx.putImageData(cutoutImgData, 0, 0);

        cutoutCanvas.toBlob(
          (b) => {
            try {
              segmenter.close();
            } catch {}
            if (!b) {
              reject(new Error('Failed to encode transparent cutout PNG.'));
              return;
            }
            resolve({
              alphaMask,
              maskCanvas,
              cutoutCanvas,
              blob: b,
              modelUsed: 'mediapipe_person',
              confidence: coverageRatio,
            });
          },
          'image/png'
        );
      } catch (err) {
        try {
          segmenter.close();
        } catch {}
        reject(err);
      }
    });

    // Send the downscaled inference source to MediaPipe graph
    segmenter.send({ image: inferenceSource }).catch((err: any) => {
      if (!hasResolved) {
        hasResolved = true;
        clearTimeout(timeoutTimer);
        try {
          segmenter.close();
        } catch {}
        reject(err);
      }
    });
  });
}

/** Max wait for the IS-Net model download + inference before giving up (slow connections need headroom). */
const IMGLY_TIMEOUT_MS = 90_000;

/**
 * Executes @imgly/background-removal IS-Net salient object segmentation.
 * Used for general objects, products, animals, and furniture.
 */
export async function executeImglySegmentation(
  file: File | Blob,
  imgElement: HTMLImageElement,
  options: { model?: 'isnet' | 'isnet_fp16' | 'isnet_quint8'; timeoutMs?: number } = {}
): Promise<AiSegmentationResult> {
  const w = Math.max(1, imgElement.naturalWidth || imgElement.width || 1);
  const h = Math.max(1, imgElement.naturalHeight || imgElement.height || 1);

  const { removeBackground: imglyRemoveBg } = await import('@imgly/background-removal');

  const modelChoice = options.model || 'isnet_quint8';
  const timeoutMs = options.timeoutMs ?? IMGLY_TIMEOUT_MS;
  let timer: ReturnType<typeof setTimeout> | undefined;
  const timeout = new Promise<never>((_, reject) => {
    timer = setTimeout(
      () =>
        reject(
          new Error(
            `AI model did not respond within ${Math.round(timeoutMs / 1000)} seconds. ` +
              'The model files are downloaded on first use, so please check your internet connection and try again.'
          )
        ),
      timeoutMs
    );
  });
  let aiBlob: Blob;
  try {
    aiBlob = await Promise.race([
      imglyRemoveBg(file, {
        publicPath: 'https://staticimgly.com/@imgly/background-removal-data/1.7.0/dist/',
        model: modelChoice,
        device: 'cpu',
      }),
      timeout,
    ]);
  } finally {
    if (timer) clearTimeout(timer);
  }

  if (!aiBlob || aiBlob.size === 0) {
    throw new Error('IS-Net segmentation returned empty result.');
  }

  const aiImg = await loadImageFromFile(aiBlob);
  const tempCanvas = document.createElement('canvas');
  tempCanvas.width = w;
  tempCanvas.height = h;
  const tempCtx = tempCanvas.getContext('2d', { willReadFrequently: true });
  if (!tempCtx) throw new Error('Canvas context unavailable');

  tempCtx.drawImage(aiImg, 0, 0, w, h);
  const aiData = tempCtx.getImageData(0, 0, w, h);
  const totalPixels = w * h;
  const alphaMask = new Uint8Array(totalPixels);

  for (let i = 0; i < totalPixels; i++) {
    alphaMask[i] = aiData.data[i * 4 + 3];
  }

  // Build cutout canvas using pristine original image colors
  const cutoutCanvas = document.createElement('canvas');
  cutoutCanvas.width = w;
  cutoutCanvas.height = h;
  const cutoutCtx = cutoutCanvas.getContext('2d', { willReadFrequently: true });
  if (!cutoutCtx) throw new Error('Cutout context unavailable');

  cutoutCtx.drawImage(imgElement, 0, 0, w, h);
  const origData = cutoutCtx.getImageData(0, 0, w, h);
  for (let i = 0; i < totalPixels; i++) {
    const a = alphaMask[i];
    const p = i * 4;
    if (a === 0) {
      origData.data[p] = 0;
      origData.data[p + 1] = 0;
      origData.data[p + 2] = 0;
      origData.data[p + 3] = 0;
    } else {
      origData.data[p + 3] = a;
    }
  }
  cutoutCtx.putImageData(origData, 0, 0);

  // Mask diagnostic canvas
  const maskCanvas = document.createElement('canvas');
  maskCanvas.width = w;
  maskCanvas.height = h;
  const maskCtx = maskCanvas.getContext('2d');
  if (maskCtx) {
    const mData = maskCtx.createImageData(w, h);
    for (let i = 0; i < totalPixels; i++) {
      const a = alphaMask[i];
      mData.data[i * 4] = a;
      mData.data[i * 4 + 1] = a;
      mData.data[i * 4 + 2] = a;
      mData.data[i * 4 + 3] = 255;
    }
    maskCtx.putImageData(mData, 0, 0);
  }

  const finalBlob = await new Promise<Blob>((resolve, reject) => {
    cutoutCanvas.toBlob(
      (b) => (b ? resolve(b) : reject(new Error('Cutout toBlob failed'))),
      'image/png'
    );
  });

  return {
    alphaMask,
    maskCanvas,
    cutoutCanvas,
    blob: finalBlob,
    modelUsed: 'imgly_isnet',
  };
}

/**
 * Universal True AI Segmentation Dispatcher.
 * Runs MediaPipe person segmentation first (optimal for portraits, outdoor people, full-body photos).
 * If MediaPipe does not detect a human or is not suitable, falls back to IS-Net object segmentation.
 * 
 * CRITICAL RULE: If AI segmentation fails, throws an explicit descriptive error.
 * NEVER silently exports the old color-tolerance algorithm!
 */
export async function executeRealAiSegmentation(
  file: File | Blob,
  imgElement: HTMLImageElement,
  options: {
    modelVariant?: 'small' | 'medium' | 'large';
    targetSubject?: 'auto' | 'person' | 'object';
  } = {}
): Promise<AiSegmentationResult> {
  const isBrowser = typeof window !== 'undefined' && typeof document !== 'undefined';
  if (!isBrowser) {
    throw new Error('AI segmentation model requires a browser runtime environment.');
  }

  let lastError: Error | null = null;

  // 1. If target is auto or person, attempt MediaPipe person segmentation first
  if (options.targetSubject !== 'object') {
    try {
      const mpResult = await executeMediaPipeSegmentation(imgElement, {
        modelSelection: 1, // Full body / outdoor landscape
      });
      return mpResult;
    } catch (err: any) {
      console.warn('MediaPipe person segmentation check:', err?.message || err);
      lastError = err instanceof Error ? err : new Error(String(err));
    }
  }

  // 2. Attempt @imgly/background-removal IS-Net salient object segmentation
  try {
    const modelChoice =
      options.modelVariant === 'large'
        ? 'isnet'
        : options.modelVariant === 'medium'
        ? 'isnet_fp16'
        : 'isnet_quint8';

    const imglyResult = await executeImglySegmentation(file, imgElement, {
      model: modelChoice,
    });
    return imglyResult;
  } catch (err: any) {
    console.warn('IS-Net salient object segmentation check:', err?.message || err);
    lastError = err instanceof Error ? err : new Error(String(err));
  }

  // 3. Fallback attempt with modelSelection 0 (close-up selfie model) if person was targeted
  try {
    const mpCloseUpResult = await executeMediaPipeSegmentation(imgElement, {
      modelSelection: 0,
    });
    return mpCloseUpResult;
  } catch (err: any) {
    lastError = err instanceof Error ? err : new Error(String(err));
  }

  // EXPLICIT FAILURE REQUIREMENT: Never silently fall back to inaccurate color-tolerance cutout!
  throw new Error(
    `AI Segmentation Engine Error: ${lastError?.message || 'Could not isolate foreground subject'}. Please use the Erase / Restore brushes to refine the mask or select Legacy Color mode for simple single-tone backgrounds.`
  );
}
