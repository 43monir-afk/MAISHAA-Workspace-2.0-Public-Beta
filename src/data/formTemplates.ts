/**
 * Helper to get fields for a template. If template has specific fields, use them,
 * otherwise return category standard fields.
 */
export function getTemplateFields(template: FormTemplate): FormFieldDefinition[] {
  if (template.fields && template.fields.length > 0) {
    return template.fields;
  }
  return getCategoryFields(template.category);
}
